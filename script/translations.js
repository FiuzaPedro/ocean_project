// Function to get current language from localStorage or default to Portuguese
function getCurrentLanguage() {
    return localStorage.getItem('language') || 'pt';
}

// Function to set current language
function setLanguage(lang) {
    localStorage.setItem('language', lang);
    applyLanguage(lang);
    updateLanguageButtons(lang);
}

// Function to apply language to all elements with data-i18n attribute
function applyLanguage(lang) {
    const elements = document.querySelectorAll('[data-i18n]');

    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        const translation = getTranslation(key, lang);

        if (translation) {
            if (element.tagName === 'INPUT' && element.type === 'placeholder') {
                element.placeholder = translation;
            } else if (element.tagName === 'A') {
                element.textContent = translation;
            } else {
                // Check if element has child elements (like icons)
                if (element.children.length > 0) {
                    // Preserve child elements, only update text nodes
                    const childNodes = Array.from(element.childNodes);
                    childNodes.forEach(node => {
                        if (node.nodeType === Node.TEXT_NODE) {
                            node.textContent = translation;
                        }
                    });
                } else {
                    element.textContent = translation;
                }
            }
        }
    });

    // Update HTML lang attribute
    document.documentElement.lang = lang;
}

// Helper function to get nested translation
function getTranslation(key, lang) {
    const keys = key.split('.');
    let value = translations[lang];
    
    for (const k of keys) {
        if (value && value[k] !== undefined) {
            value = value[k];
        } else {
            return null;
        }
    }
    
    return value;
}

// Function to update language button active states
function updateLanguageButtons(activeLang) {
    const buttons = document.querySelectorAll('.lang-btn');
    
    buttons.forEach(button => {
        if (button.getAttribute('data-lang') === activeLang) {
            button.classList.add('active');
        } else {
            button.classList.remove('active');
        }
    });
}

// Initialize language on page load
function initLanguage() {
    const currentLang = getCurrentLanguage();
    applyLanguage(currentLang);
    updateLanguageButtons(currentLang);
}

// Add event listeners to language buttons
function initLanguageSwitcher() {
    const buttons = document.querySelectorAll('.lang-btn');
    
    buttons.forEach(button => {
        button.addEventListener('click', function() {
            const lang = this.getAttribute('data-lang');
            setLanguage(lang);
        });
    });
}

// Call initialization functions when DOM is loaded
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        initLanguage();
        initLanguageSwitcher();
    });
} else {
    initLanguage();
    initLanguageSwitcher();
}
